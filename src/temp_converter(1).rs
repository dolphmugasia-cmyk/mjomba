    let fahrenheit = (celsius * 9.0 / 5.0) + 32.0;
    println!("{}°C is equal to {}°F", celsius, fahrenheit);

    //convert Fahrenheit to Celsius
    let fahrenheit = 98.6;
    let celsius = (fahrenheit - 32.0) * 5.0 / 9.0;
    println!("{}°F is equal to {}°C", fahrenheit, celsius);

